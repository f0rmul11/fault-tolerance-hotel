// Package outbox записывает Kafka-событие и выбранную партицию в транзакции
// бизнес-операции. Handler задаёт число партиций. До старта сервиса в Kafka
// должны существовать эти партиции, а в outbox_offsets — курсоры 0..N-1.
// Их добавляют миграцией сервиса.
//
// За тик воркер обрабатывает одну страницу каждой партиции. У каждой страницы
// своя транзакция и блокировка курсора. После ACK всей страницы воркер сдвигает
// курсор. Сбой между ACK и commit допускает повтор с тем же correlation-id.
// Страница читается ниже xmin снимка. Долгоживущая транзакция с ранним XID
// может задержать видимость новых сообщений во всех партициях.
//
// Добавление партиций в Kafka само по себе не меняет маршрут. Для смены
// PartitionsCount остановите все источники записи, дождитесь завершения открытых
// транзакций, опустошения outbox и обработки старых сообщений потребителями.
// Добавьте партиции и курсоры, обновите конфигурацию всех реплик и возобновите
// запись. При переходе с v1 сначала дочитайте очередь v1 тем же способом.
