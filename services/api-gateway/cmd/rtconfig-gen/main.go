// rtconfig-gen создаёт facade из service YAML и платформенного registry.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"go/token"
	"io"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"api-gateway/internal/pkg/rtconfig"
	"api-gateway/internal/pkg/rtconfig/system"
)

func main() {
	if err := run(os.Args[1:], os.Stderr); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(args []string, stderr io.Writer) error {
	flags := flag.NewFlagSet("rtconfig-gen", flag.ContinueOnError)
	flags.SetOutput(stderr)
	schemaPath := flags.String("schema", "config/rtconfig.yaml", "service realtimeConfig YAML")
	outPath := flags.String("out", "internal/config/config.go", "generated Go file")
	if err := flags.Parse(args); err != nil {
		return err
	}
	if flags.NArg() != 0 {
		return fmt.Errorf("rtconfig-gen: unexpected positional arguments")
	}

	data, err := os.ReadFile(*schemaPath)
	if err != nil {
		return fmt.Errorf("read schema: %w", err)
	}
	schema, err := mergedSchema(data, system.Definitions())
	if err != nil {
		return err
	}
	source, err := generate(schema)
	if err != nil {
		return err
	}

	return writeGenerated(*outPath, source)
}

func mergedSchema(data []byte, platform []rtconfig.Definition) (*rtconfig.Schema, error) {
	service, err := rtconfig.ParseSchema(data)
	if err != nil {
		return nil, fmt.Errorf("parse service schema: %w", err)
	}

	definitions := append(service.Definitions(), platform...)
	schema, err := rtconfig.NewSchema(definitions...)
	if err != nil {
		return nil, fmt.Errorf("merge service and platform schema: %w", err)
	}

	return schema, nil
}

func generate(schema *rtconfig.Schema) ([]byte, error) {
	reserved := map[string]string{
		"Client":     "generated facade",
		"NewClient":  "generated constructor",
		"GetValue":   "generated accessor",
		"SchemaHash": "generated schema hash",
	}
	var constants bytes.Buffer
	for _, definition := range schema.Definitions() {
		name := goName(definition.Name)
		if !token.IsIdentifier(name) || token.Lookup(name).IsKeyword() {
			return nil, fmt.Errorf("key %q: invalid Go identifier %q", definition.Name, name)
		}
		if previous, exists := reserved[name]; exists {
			return nil, fmt.Errorf("key %q: Go identifier %q conflicts with %s", definition.Name, name, previous)
		}
		reserved[name] = strconv.Quote(definition.Name)

		for _, line := range strings.Split(strings.ReplaceAll(definition.Usage, "\r", ""), "\n") {
			if line != "" {
				fmt.Fprintf(&constants, "\t// %s\n", line)
			}
		}
		fmt.Fprintf(&constants, "\t%s = configKey(%q)\n", name, definition.Name)
	}

	var source bytes.Buffer
	fmt.Fprintf(&source, `// Code generated by "rtconfig-gen". DO NOT EDIT.

package config

import (
	"context"

	"api-gateway/internal/pkg/rtconfig"
	"api-gateway/internal/pkg/rtconfig/global"
)

type configKey string

const (
%s)

// SchemaHash соответствует объединённому service/system каталогу генерации.
// Bootstrap сверяет его с schema.Hash() до установки клиента и serving.
const SchemaHash = %q

// GetValue читает явно установленный global client, без I/O или логов.
// global.SetClient нельзя подменять в parallel tests; используйте NewClient.
func GetValue(ctx context.Context, key configKey) rtconfig.Value {
	return getValue(global.Client(), ctx, key)
}

// Client позволяет внедрить независимый клиент, в том числе в parallel tests.
type Client struct {
	client rtconfig.Client
}

func NewClient(c rtconfig.Client) *Client {
	if c == nil {
		panic("config: nil realtime config client")
	}

	return &Client{client: c}
}

func (c *Client) GetValue(ctx context.Context, key configKey) rtconfig.Value {
	return getValue(c.client, ctx, key)
}

func getValue(client rtconfig.Client, ctx context.Context, key configKey) rtconfig.Value {
	v, err := client.Value(ctx, string(key))
	if err != nil {
		return rtconfig.NewNilValue(err)
	}

	return v
}
`, constants.String(), schema.Hash())

	formatted, err := format.Source(source.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated config: %w", err)
	}

	return formatted, nil
}

func goName(name string) string {
	parts := strings.Split(name, "_")
	for i, part := range parts {
		switch part {
		case "id", "http", "url", "sql", "rpc", "tls", "cpu", "json", "yaml":
			parts[i] = strings.ToUpper(part)
		case "grpc":
			parts[i] = "GRPC"
		default:
			if part != "" {
				parts[i] = strings.ToUpper(part[:1]) + part[1:]
			}
		}
	}

	return strings.Join(parts, "")
}

func writeGenerated(path string, data []byte) error {
	directory := filepath.Dir(path)
	if err := os.MkdirAll(directory, 0o755); err != nil {
		return fmt.Errorf("create output directory: %w", err)
	}
	file, err := os.CreateTemp(directory, ".rtconfig-*.go")
	if err != nil {
		return fmt.Errorf("create temporary output: %w", err)
	}
	temporary := file.Name()
	defer os.Remove(temporary)

	if _, err := file.Write(data); err != nil {
		file.Close()
		return fmt.Errorf("write generated config: %w", err)
	}
	if err := file.Chmod(0o644); err != nil {
		file.Close()
		return fmt.Errorf("set generated config mode: %w", err)
	}
	if err := file.Close(); err != nil {
		return fmt.Errorf("close generated config: %w", err)
	}
	if err := os.Rename(temporary, path); err != nil {
		return fmt.Errorf("replace generated config: %w", err)
	}

	return nil
}
